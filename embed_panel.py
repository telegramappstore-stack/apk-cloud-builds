#!/usr/bin/env python3
"""Bakes aminium-pages.zip into the app so nobody ever has to pick a file.

    python embed_panel.py aminium-pages.zip      # writes panel_data.py next to this script

Commit panel_data.py together with main.py / aminium_core.py. Python files are always packed
into the APK, so the panel travels inside the app and Step 3 uses it automatically.
"""
import base64
import sys
import zipfile
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else "aminium-pages.zip")
if not src.is_file():
    sys.exit(f"not found: {src}")
with zipfile.ZipFile(src) as z:
    names = [n.replace("\\", "/") for n in z.namelist()]
if not any(n == "_worker.js" or n.endswith("/_worker.js") for n in names):
    sys.exit("this zip has no _worker.js - wrong file?")
b64 = base64.b64encode(src.read_bytes()).decode()
lines = "\n".join(b64[i:i + 100] for i in range(0, len(b64), 100))
out = Path(__file__).resolve().parent / "panel_data.py"
out.write_text('"""Generated by embed_panel.py - do not edit."""\nPANEL_ZIP_B64 = """\n' + lines + '\n"""\n', encoding="utf-8")
print(f"OK: {out}  ({len(b64) // 1024} KB base64, {len(names)} files inside)")
